import type { Database } from "bun:sqlite";

/**
 * The control plane's record of what each runner serves (§15.1).
 *
 * The runner is the registration authority: every successful hello and
 * reconcile carries the full declaration, and this module replaces the
 * runner's rows with it. Nothing here accumulates history — a workspace the
 * current boot does not declare has no row, which is what keeps placement
 * from routing work to a directory the runner no longer vouches for.
 */

export type DeclaredWorkspaceRow = {
  workspaceId: string;
  path: string;
  /** The workspace's local heads at declaration time (M4); absent = none known. */
  branches?: string[];
  /** The head HEAD pointed at when declared; absent = unknown. Display only. */
  currentBranch?: string;
};

export type OwnerWorkspace = {
  workspaceId: string;
  runnerId: string;
  path: string;
  branches: string[];
  /** Null when the runner did not say (older runner, non-repo, detached HEAD). */
  currentBranch: string | null;
  createdAt: number;
};

/**
 * Register a single custom workspace for a runner (§15.1 Task 8).
 *
 * Unlike `upsertRunnerWorkspaces`, which is a declarative replace driven by
 * the runner's hello/reconcile, this is a control-plane write: an owner
 * registers a folder the runner should be able to address as a workspace.
 * The row lands in the same `workspaces` table so `workspacesForOwner` and
 * the ownership check in `handleBrowse`/`handleWorkspaceSessions*` see it.
 *
 * `workspaceId` is generated by the control plane (a UUID) so a custom path
 * is addressable by a stable id before the runner ever reconciles it back.
 *
 * Idempotent by (runnerId, workspaceId): re-registering with the same
 * workspace id replaces the path in place, never duplicates the row.
 */
export function registerWorkspace(
  db: Database,
  runnerId: string,
  workspaceId: string,
  path: string,
): void {
  db.prepare(
    `INSERT INTO workspaces (runner_id, workspace_id, path, branches, registered_at, is_custom)
     VALUES (?, ?, ?, '[]', ?, 1)
     ON CONFLICT (runner_id, workspace_id) DO UPDATE SET path = excluded.path`,
  ).run(runnerId, workspaceId, path, Date.now());
}

/**
 * Replace a runner's declared workspaces. One transaction: a crash between the
 * delete and the insert must not leave the runner with no rows when it just
 * declared some (an empty declaration after a non-empty one is a real state,
 * but a crash-shaped hole is not).
 *
 * A declared id may collide with a custom row the owner registered earlier: the
 * control plane mints that row's id, hands it to the runner with the run, and
 * the runner redeclares the very same id at its next hello. The row becomes
 * declared — the runner is the registration authority — so the insert upserts
 * instead of throwing on the primary key (a throw here would escape the hello
 * handler and drop the runner's socket).
 */
export function upsertRunnerWorkspaces(
  db: Database,
  runnerId: string,
  workspaces: readonly DeclaredWorkspaceRow[],
): void {
  const replace = db.transaction(() => {
    db.prepare("DELETE FROM workspaces WHERE runner_id = ? AND is_custom = 0").run(runnerId);
    const insert = db.prepare(
      `INSERT INTO workspaces
         (runner_id, workspace_id, path, branches, current_branch, registered_at, is_custom)
       VALUES (?, ?, ?, ?, ?, ?, 0)
       ON CONFLICT (runner_id, workspace_id) DO UPDATE SET
         path = excluded.path,
         branches = excluded.branches,
         current_branch = excluded.current_branch,
         registered_at = excluded.registered_at,
         is_custom = 0`,
    );
    const now = Date.now();
    for (const workspace of workspaces) {
      insert.run(
        runnerId,
        workspace.workspaceId,
        workspace.path,
        JSON.stringify(workspace.branches ?? []),
        workspace.currentBranch ?? null,
        now,
      );
    }
  });
  replace();
}

/**
 * The `branches` column as a typed list. The writer is ours, but reads never
 * throw: a hand-migrated or corrupted row reads as "no branches known" —
 * placement and the composer degrade, the control plane does not.
 */
function branchesOf(raw: string): string[] {
  try {
    const parsed = JSON.parse(raw) as unknown;
    if (!Array.isArray(parsed)) return [];
    return parsed.filter((entry): entry is string => typeof entry === "string");
  } catch {
    return [];
  }
}

/**
 * The owner's workspaces across every runner they still hold, oldest runner
 * first — the stable order GET /api/workspaces and placement both read.
 */
export function workspacesForOwner(db: Database, ownerId: string): OwnerWorkspace[] {
  const rows = db
    .prepare(
      `SELECT w.workspace_id, w.runner_id, w.path, w.branches, w.current_branch, r.created_at
       FROM workspaces w
       JOIN runners r ON r.id = w.runner_id
       WHERE r.owner_id = ? AND r.revoked_at IS NULL
       ORDER BY r.created_at ASC, w.workspace_id ASC`,
    )
    .all(ownerId) as Array<{
    workspace_id: string;
    runner_id: string;
    path: string;
    branches: string;
    current_branch: string | null;
    created_at: number;
  }>;
  return rows.map((row) => ({
    workspaceId: row.workspace_id,
    runnerId: row.runner_id,
    path: row.path,
    branches: branchesOf(row.branches),
    currentBranch: row.current_branch,
    createdAt: row.created_at,
  }));
}

#!/usr/bin/env bun
/**
 * Generates the SDK CLI asset shim for one build target (§20.3).
 *
 * A `bun build --compile` binary cannot resolve the Agent SDK's native CLI at
 * runtime — the README-documented recipe embeds the platform package's binary
 * as a file asset and extracts it before spawning. The asset specifier must be
 * static for the bundler, so which platform package gets embedded is decided
 * HERE, per build: this script writes the one-line shim the adapter imports.
 *
 * The shim is generated, never committed: every `bun install` (postinstall)
 * regenerates it for the host (bundled by default), and every `build:runner`
 * regenerates it for the requested `--target` and variant — a cross-compiled
 * binary can never inherit the host's CLI.
 *
 * The CLI path is overridable so tests can generate into a temp directory
 * without disturbing the shim the rest of the process imports.
 *
 *   bun run scripts/claude-asset.ts [--target bun-windows-x64]
 */

import { claudeAssetTarget } from "../packages/agent-adapter/src/claude-asset-targets.ts";

const SHIM_PATH = new URL(
  "../packages/agent-adapter/src/claude-asset.generated.ts",
  import.meta.url,
).pathname;

export type ClaudeAssetVariant = "slim" | "bundled";

export async function generateShim(
  target: string,
  variant: ClaudeAssetVariant = "bundled",
  outPath: string = SHIM_PATH,
): Promise<void> {
  if (variant === "slim") {
    await Bun.write(
      outPath,
      `// GENERATED by scripts/claude-asset.ts — do not edit, do not commit.
// Slim build: no CLI is embedded; the runner uses the host's \`claude\`.
export const asset = { kind: "external" } as const;
`,
    );
    return;
  }
  const asset = claudeAssetTarget(target);
  await Bun.write(
    outPath,
    `// GENERATED by scripts/claude-asset.ts — do not edit, do not commit.
// Regenerated on every \`bun install\` (postinstall) and every \`build:runner\`.
import binPath from "${asset.pkg}/${asset.binary}" with { type: "file" };
export const asset = { kind: "embedded", binPath } as const;
`,
  );
}

/** The `--target` of this CLI, or `"host"` when it is not given at all. */
export function parseTargetArg(argv: readonly string[]): string {
  // `--target=x` is accepted as one word by build:runner; this CLI must not
  // silently fall back to "host" when someone uses the same spelling here.
  const inline = argv.find((a) => a.startsWith("--target="));
  const flagIndex = argv.indexOf("--target");
  const target = inline?.slice("--target=".length) ?? argv[flagIndex + 1];
  if (flagIndex === -1 && inline === undefined) return "host";
  // Empty, or followed by another flag: both mean the value is missing, and
  // neither may fall through to the host default — a cross-compile would then
  // silently embed the wrong platform's binary.
  if (target === undefined || target.trim() === "" || target.startsWith("--")) {
    throw new Error("--target requires a value, e.g. --target bun-linux-x64");
  }
  return target;
}

if (import.meta.main) {
  const target = parseTargetArg(process.argv.slice(2));
  await generateShim(target);
  console.log(`claude-asset shim generated for ${target}`);
}

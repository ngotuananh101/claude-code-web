#!/usr/bin/env bun
/**
 * Generates the SDK CLI asset shim for one build target (§20.3).
 *
 * A `bun build --compile` binary cannot resolve the Agent SDK's native CLI at
 * runtime — the README-documented recipe embeds the platform package's binary
 * as a file asset and extracts it before spawning. The asset specifier must be
 * static for the bundler, so which platform package gets embedded is decided
 * HERE, per build: this script writes the one-line shim the adapter imports.
 *
 * The shim is generated, never committed: every `bun install` (postinstall)
 * regenerates it for the host, and every `build:runner` regenerates it for the
 * requested `--target` — a cross-compiled binary can never inherit the host's
 * CLI.
 *
 *   bun run scripts/claude-asset.ts [--target bun-windows-x64]
 */

import { claudeAssetTarget } from "../packages/agent-adapter/src/claude-asset-targets.ts";

const SHIM_PATH = new URL(
  "../packages/agent-adapter/src/claude-asset.generated.ts",
  import.meta.url,
).pathname;

/** Write the shim naming `target`'s platform binary. Exported for build:runner. */
export async function generateShim(target: string): Promise<void> {
  const asset = claudeAssetTarget(target);
  const content = `// GENERATED by scripts/claude-asset.ts — do not edit, do not commit.
// Regenerated on every \`bun install\` (postinstall) and every \`build:runner\`.
import binPath from "${asset.pkg}/${asset.binary}" with { type: "file" };
export default binPath;
`;
  // Awaited so callers can rely on the file being on disk when the promise
  // resolves — build:runner compiles immediately after.
  await Bun.write(SHIM_PATH, content);
}

if (import.meta.main) {
  const argv = process.argv.slice(2);
  const flagIndex = argv.indexOf("--target");
  const target =
    flagIndex === -1
      ? "host"
      : (argv[flagIndex + 1] ??
        (() => {
          throw new Error("--target requires a value, e.g. --target bun-linux-x64");
        })());
  await generateShim(target);
  console.log(`claude-asset shim generated for ${target}`);
}
